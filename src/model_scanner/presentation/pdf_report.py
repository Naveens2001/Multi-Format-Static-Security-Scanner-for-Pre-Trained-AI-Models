"""
model_scanner.presentation.pdf_report
======================================

Optional PDF report renderer for professional security assessments.

PDF generation requires the ``weasyprint`` library, available as an
optional extra::

    pip install "model-scanner[report]"

If weasyprint is not installed, ``PDFReportRenderer.render()`` raises
``ImportError`` with a clear installation message.

FALLBACK (no weasyprint)
------------------------
The HTML report generated by ``HTMLReportRenderer`` includes full
``@media print`` and ``@page`` CSS rules and is directly usable as a
PDF source via any browser's Print → Save as PDF function.

SECURITY GUARANTEE
------------------
This module is a PURE PRESENTATION ADAPTER.
It NEVER executes model code, deserializes binary, or makes network requests.
The PDF is derived exclusively from a pre-built ReportModel.
"""

from __future__ import annotations

from pathlib import Path

from model_scanner.presentation.html_report import HTMLReportRenderer
from model_scanner.presentation.report_model import ReportModel


class PDFReportRenderer:
    """Export a ReportModel as a PDF document (requires model-scanner[report])."""

    @staticmethod
    def render(report: ReportModel, destination: str | Path) -> None:
        """Write the PDF report to *destination*.

        Parameters
        ----------
        report:
            The read-only derived ReportModel.
        destination:
            Output file path (e.g. ``report.pdf``).

        Raises
        ------
        ImportError
            If ``weasyprint`` is not installed.
        """
        try:
            import weasyprint as _wp  # type: ignore[import-not-found]
        except ImportError as exc:
            raise ImportError(
                "PDF generation requires the 'weasyprint' library. "
                "Install it with: pip install 'model-scanner[report]'\n\n"
                "Alternatively, open the HTML report in any browser and use "
                "File - Print - Save as PDF to generate a PDF with full styling."
            ) from exc

        html_content = HTMLReportRenderer.render(report)
        dest_path = Path(destination)
        dest_path.parent.mkdir(parents=True, exist_ok=True)
        _wp.HTML(string=html_content).write_pdf(str(dest_path))

    @staticmethod
    def is_available() -> bool:
        """Return True if weasyprint is installed and PDF rendering is available."""
        try:
            import weasyprint  # type: ignore[import-not-found, unused-ignore]  # noqa: F401
            return True
        except ImportError:
            return False


__all__ = [
    "PDFReportRenderer",
]
